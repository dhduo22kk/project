    LEFT JOIN M_CMP_CR_CLM_CRST B ON A.CTMNO = B.NRDPS_CTMNO
    INNER JOIN M_CMP_CR_CMP_CLM_CR C
        ON B.RCPDT = C.RCPDT AND B.RCP_NV_SEQNO = C.RCP_NV_SEQNO
        AND C.CLMDT BETWEEN F_LAST_DAY(F_PREV_MONTH(T.CLS_YYMM,'60')) AND FIRST_DAY(T.CLS_YYMM)
