/* ============================================================================
   [1] 전체 계약 + 채널 + GD_TYPE
   ※ CHNL: DATABIZ_FUTVAL_STF_CHNL_MAP 재사용 (이전월 org 기준)
   ※ GD_TYPE: GDREC_TMGD_LIST JOIN → 하위 PL_PRED/CR_GD_PRED CASE WHEN 제거
============================================================================ */
DROP TABLE DATABIZ_FUTVAL_ALL_CR_TEMP_PRED PURGE;
CREATE TABLE DATABIZ_FUTVAL_ALL_CR_TEMP_PRED AS
SELECT A.*, B.CHNL, G.GD_TYPE
FROM DATABIZ_FUTVAL_YYMM_PRED T
LEFT JOIN M_CRM_MTHY_PS_CR A
    ON A.CLS_YYMM = T.CLS_YYMM
LEFT JOIN DATABIZ_FUTVAL_STF_CHNL_MAP B
    ON F_PREV_MONTH(T.CLS_YYMM,'-1') = B.CLS_YYMM
    AND A.DH_STFNO = B.STFNO
LEFT JOIN GDREC_TMGD_LIST G
    ON A.GDCD = G.GDCD;


/* ============================================================================
   [2] 고객 기본정보 (계약자/피보험자 연령·성별·보험종류)
   ※ F_BIRTH_DAY_DEC/F_SEX_DEC: 서브쿼리에서 1회 호출 후 GROUP BY에서 재사용
============================================================================ */
DROP TABLE DATABIZ_FUTVAL_ALL_CUS_INFO_PRED PURGE;
CREATE TABLE DATABIZ_FUTVAL_ALL_CUS_INFO_PRED AS
SELECT
    CLS_YYMM, CTMNO, DH_STFNO, RELPC_TPCD
    , CASE WHEN F_ISDATE(BRTH) = 'T'
           THEN TRUNC(MONTHS_BETWEEN(F_LAST_DAY(CLS_YYMM), TO_DATE(BRTH,'YYYYMMDD')) / 12)
      END AS CTM_AGE
    , CASE WHEN SEX = 'M' THEN '1.M' WHEN SEX = 'F' THEN '2.F' END AS CTM_SEX
    , MAX(CASE WHEN IKD_GRPCD = 'LA'       THEN 1 ELSE 0 END) AS LA_YN
    , MAX(CASE WHEN IKD_GRPCD = 'CA'       THEN 1 ELSE 0 END) AS CA_YN
    , MAX(CASE WHEN IKD_GRPCD IN ('FA','MA') THEN 1 ELSE 0 END) AS FAMA_YN
FROM (
    SELECT A.CLS_YYMM, A.DH_STFNO,
           C.CTMNO, C.RELPC_TPCD, C.IKD_GRPCD,
           F_BIRTH_DAY_DEC(C.CTM_DSCNO) AS BRTH,
           F_SEX_DEC(C.CTM_DSCNO)       AS SEX
    FROM DATABIZ_FUTVAL_ALL_CR_TEMP_PRED A
    INNER JOIN DATABIZ_FUTVAL_YYMM_PRED T ON A.CLS_YYMM = T.CLS_YYMM
    INNER JOIN INS_CR_RELPC C
        ON A.PLYNO = C.PLYNO
        AND C.NDS_AP_STR_DTHMS <= T.CLS_NDDT
        AND C.NDS_AP_ND_DTHMS   > T.CLS_NDDT
        AND C.RELPC_TPCD IN ('01','02')
        AND C.RELPC_STCD IN ('01','04')
)
GROUP BY CLS_YYMM, CTMNO, DH_STFNO, RELPC_TPCD, BRTH, SEX;


/* ============================================================================
   [3] 직업 분류
   ※ SPJOB_YN: LIKE 30개 → REGEXP_LIKE 2개 (포함/제외)
   ※ ON 0=0 → 직접 JOIN 조건
