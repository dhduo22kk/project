          OR (BR_ORGCD = '1301040' AND BZP_ORGCD='1301396')
          OR (BR_ORGCD = '1300090' AND BZP_ORGCD='1301384')              THEN '20'
        WHEN STFNO = '8066063' AND BZP_ORGCD = '1301581'                 THEN '31'
