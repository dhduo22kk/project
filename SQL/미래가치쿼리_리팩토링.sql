   [4] 고객 주소 + 직업코드
============================================================================ */
DROP TABLE DATABIZ_FUTVAL_CUS_ADD_PRED PURGE;
CREATE TABLE DATABIZ_FUTVAL_CUS_ADD_PRED AS
SELECT
    A1.CLS_YYMM, A1.CTMNO, CTM_SEX
    , CASE WHEN CTM_AGE BETWEEN 18 AND 29 THEN '20대 이하'
           WHEN CTM_AGE BETWEEN 30 AND 39 THEN '30대'
           WHEN CTM_AGE BETWEEN 40 AND 49 THEN '40대'
           WHEN CTM_AGE BETWEEN 50 AND 59 THEN '50대'
           WHEN CTM_AGE BETWEEN 60 AND 99 THEN '60대 이상'
           ELSE NULL END AS AGE_CD
    , CTM_AGE, SD, SGNG, PSTNO, PSTNO_ID
    , E.JBCD, E.JB_CH_SEQNO, F.JBNM
FROM (
    SELECT DISTINCT
        T.CLS_YYMM, T.CTMNO, T.CTM_SEX, T.CTM_AGE
        , A.SD, A.SGNG, A.PSTNO
        , COALESCE(B.PSTNO_ID, C.PSTNO_ID, D.PSTNO_ID) AS PSTNO_ID
        , ROW_NUMBER() OVER (
            PARTITION BY T.CLS_YYMM, T.CTMNO
            ORDER BY A.AP_STR_DTHMS DESC,
                     CASE WHEN B.PSTNO_ID IS NULL THEN 1 ELSE 0 END,
                     CASE WHEN C.PSTNO_ID IS NULL THEN 1 ELSE 0 END
          ) AS RK
    FROM DATABIZ_FUTVAL_ALL_CUS_INFO_PRED T
    INNER JOIN CUS_CTM_ADR_CRR A
        ON T.CTMNO = A.CTMNO
        AND A.AP_ND_DTHMS  >= F_LAST_DAY(T.CLS_YYMM)
        AND A.AP_STR_DTHMS  < F_LAST_DAY(T.CLS_YYMM)
        AND A.ADR_FLGCD = '100'
    LEFT JOIN CUS_PSTNO_RODNM_BA_ADR B ON A.BLD_ADMNO = B.BLD_ADMNO
    LEFT JOIN CUS_PSTNO_RODNM_BA_ADR C
        ON A.PSTNO = C.PSTNO AND A.SD = C.SD AND A.SGNG = C.SGNG
        AND A.ROAD_NM = C.ROAD_NM AND A.MN_BLDNO = C.MN_BLDNO
        AND COALESCE(A.SUB_BLDNO,'0') = COALESCE(C.SUB_BLDNO,'0')
    LEFT JOIN CUS_PSTNO_RODNM_BA_ADR D
        ON A.PSTNO = D.PSTNO AND A.SD = D.SD AND A.SGNG = D.SGNG
        AND A.ROAD_NM = D.ROAD_NM AND A.MN_BLDNO = D.MN_BLDNO
) A1
LEFT JOIN CUS_CTM_JB_CRR E
    ON A1.CTMNO = E.CTMNO
    AND E.AP_STR_DTHMS <= F_LAST_DAY(A1.CLS_YYMM)
    AND E.AP_ND_DTHMS   > F_LAST_DAY(A1.CLS_YYMM)
LEFT JOIN CUS_JB F
    ON E.JBCD = F.JBCD AND E.JB_CH_SEQNO = F.JB_CH_SEQNO
WHERE RK = 1;


