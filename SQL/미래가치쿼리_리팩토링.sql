SELECT
    CLS_YYMM, STFNO,
    CASE
        WHEN STFNO = '8901911'                                            THEN '61'
        WHEN STFNO = '6009607'                                            THEN '11'
        WHEN BZ_ATRCD IN ('30','31')                                      THEN '62'
