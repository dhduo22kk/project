        WHEN TMNM LIKE '%한생GA팀%'                                        THEN '20'
        WHEN BZ_FML_QUFCD IN ('G01')                                      THEN '20'
        WHEN BZ_ATRCD IN ('15','16','18','97','27')                       THEN '12'
